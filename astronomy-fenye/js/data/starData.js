export function raDecToVector3(ra, dec, radius = 100) {
  const raRad = (ra * Math.PI) / 180;
  const decRad = (dec * Math.PI) / 180;
  const x = radius * Math.cos(decRad) * Math.cos(raRad);
  const y = radius * Math.sin(decRad);
  const z = radius * Math.cos(decRad) * Math.sin(raRad);
  return new THREE.Vector3(x, y, z);
}

export function eclipticToEquatorial(lambda, beta) {
  const epsilon = (23.4397 * Math.PI) / 180;
  const lambdaRad = (lambda * Math.PI) / 180;
  const betaRad = (beta * Math.PI) / 180;
  const sinDec = Math.sin(betaRad) * Math.cos(epsilon) + Math.cos(betaRad) * Math.sin(epsilon) * Math.sin(lambdaRad);
  const cosDec = Math.sqrt(1 - sinDec * sinDec);
  const sinRA = (Math.cos(betaRad) * Math.sin(lambdaRad) * Math.cos(epsilon) - Math.sin(betaRad) * Math.sin(epsilon)) / cosDec;
  const cosRA = Math.cos(lambdaRad) * Math.cos(betaRad) / cosDec;
  let ra = Math.atan2(sinRA, cosRA);
  if (ra < 0) ra += 2 * Math.PI;
  const dec = Math.asin(sinDec);
  return { ra: (ra * 180) / Math.PI, dec: (dec * 180) / Math.PI };
}

export function equatorialToEcliptic(ra, dec) {
  const epsilon = (23.4397 * Math.PI) / 180;
  const raRad = (ra * Math.PI) / 180;
  const decRad = (dec * Math.PI) / 180;
  const sinBeta = Math.sin(decRad) * Math.cos(epsilon) - Math.cos(decRad) * Math.sin(epsilon) * Math.sin(raRad);
  const cosBeta = Math.sqrt(1 - sinBeta * sinBeta);
  const sinLambda = (Math.cos(decRad) * Math.sin(raRad) * Math.cos(epsilon) + Math.sin(decRad) * Math.sin(epsilon)) / cosBeta;
  const cosLambda = Math.cos(raRad) * Math.cos(decRad) / cosBeta;
  let lambda = Math.atan2(sinLambda, cosLambda);
  if (lambda < 0) lambda += 2 * Math.PI;
  const beta = Math.asin(sinBeta);
  return { lambda: (lambda * 180) / Math.PI, beta: (beta * 180) / Math.PI };
}

export function equatorialToHorizontal(ra, dec, lst, lat) {
  const raRad = (ra * Math.PI) / 180;
  const decRad = (dec * Math.PI) / 180;
  const latRad = (lat * Math.PI) / 180;
  const lstRad = (lst * Math.PI) / 180;
  const ha = lstRad - raRad;
  const sinAlt = Math.sin(latRad) * Math.sin(decRad) + Math.cos(latRad) * Math.cos(decRad) * Math.cos(ha);
  const alt = Math.asin(sinAlt);
  const cosAz = (Math.sin(decRad) - Math.sin(latRad) * sinAlt) / (Math.cos(latRad) * Math.cos(alt));
  const sinAz = -Math.cos(decRad) * Math.sin(ha) / Math.cos(alt);
  let az = Math.atan2(sinAz, cosAz);
  if (az < 0) az += 2 * Math.PI;
  return { az: (az * 180) / Math.PI, alt: (alt * 180) / Math.PI };
}

