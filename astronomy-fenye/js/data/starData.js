function generateTrajectory(centerRA, centerDec, spanRA = 15, spanDec = 5, steps = 40) {
  const points = [];
  for (let i = 0; i < steps; i++) {
    const t = i / (steps - 1);
    const ra = centerRA + (t - 0.5) * spanRA;
    const dec = centerDec + Math.sin(t * Math.PI * 2) * spanDec * 0.5;
    points.push({ ra, dec });
  }
  return points;
}

